"""Learn the scoring weights from feedback on past matches.

There is no real feedback data (and none may be used), so this module simulates
it. The idea is the one a real system would follow:

1. Families have preferences nobody wrote down. Here they are a hidden set of
   weights, HIDDEN_WEIGHTS, that the simulator uses to decide whether a match
   went well. The engine never sees them.
2. Past matches are generated by running the normal engine. Mostly the top nurse
   is assigned, sometimes a lower-ranked one (see `explore` below).
3. Each past match gets an outcome, "went well" or not, drawn from the hidden
   preferences plus luck.
4. A logistic regression is fitted on (factor values -> outcome). Its coefficients
   say how much each factor mattered, and become the new weights.
5. We check, on requests the model never saw, whether ranking with the learned
   weights puts better nurses first than the hand-set weights do.

Because the outcomes come from a known linear rule, this shows that the pipeline
recovers what it is meant to recover. It says nothing about how well it would do
on real feedback.

    python -m matcher.learning
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression

from .data_gen import generate_requests
from .dataset import load_dataset
from .engine import match
from .models import CareRequest, Nurse
from .scoring import DEFAULT_WEIGHTS, Weights, weighted_contributions

FACTORS = ("distance", "rating", "experience", "continuity")

# The invented "true" preferences used only by the simulator: in this scenario
# families care less about distance than the default weights assume, and more
# about rating and experience.
HIDDEN_WEIGHTS = Weights(distance=0.10, rating=0.40, experience=0.20, continuity=0.30)

# Chance of a good outcome = sigmoid(SLOPE * (hidden score - MIDPOINT)).
# With these values a mediocre match succeeds about half the time and an excellent
# one about nine times in ten.
SATISFACTION_SLOPE = 8.0
SATISFACTION_MIDPOINT = 0.5

TRAIN_SEEDS = (1000, 1001, 1002)
TRAIN_SIZES = (50, 100, 250, 500, 1000, 2000)


@dataclass(frozen=True)
class PastMatch:
    shown_rank: int
    factors: dict[str, float]
    went_well: int


def satisfaction_probability(factors: dict[str, float], hidden: Weights = HIDDEN_WEIGHTS) -> float:
    score = sum(weighted_contributions(factors, hidden).values())
    return float(1.0 / (1.0 + np.exp(-SATISFACTION_SLOPE * (score - SATISFACTION_MIDPOINT))))


def simulate_history(
    nurses: Sequence[Nurse],
    n_requests: int,
    seed: int,
    hidden: Weights = HIDDEN_WEIGHTS,
    explore: float = 0.4,
) -> list[PastMatch]:
    """Past matches and how they went.

    Each request is ranked with the default weights. The top nurse is assigned
    with probability 1 - explore, otherwise one of ranks 2-5 at random. Without
    that, the data would only ever contain top-ranked nurses, and a model cannot
    learn what makes a nurse good from examples where the choice never varied.
    """
    rng = np.random.default_rng(seed)
    history = []
    for request in generate_requests(list(nurses), n_requests, seed=seed):
        result = match(request, nurses, top_k=5)
        if not result.matches:
            continue
        if len(result.matches) == 1 or rng.random() >= explore:
            chosen = result.matches[0]
        else:
            chosen = result.matches[int(rng.integers(1, len(result.matches)))]
        p = satisfaction_probability(chosen.factors, hidden)
        history.append(PastMatch(chosen.rank, chosen.factors, int(rng.random() < p)))
    return history


def fit_weights(history: Sequence[PastMatch]) -> Weights:
    """Logistic regression on the factor values, coefficients turned into weights.

    A coefficient below zero would mean "more of this made outcomes worse", which
    for these four factors is not a sensible rule, so it is set to zero rather
    than used. The rest are scaled to add up to 1.
    """
    y = np.array([p.went_well for p in history])
    if len(set(y)) < 2:
        raise ValueError("Need both good and bad outcomes in the feedback to learn from it.")
    X = np.array([[p.factors[f] for f in FACTORS] for p in history])

    model = LogisticRegression(C=10.0, max_iter=1000).fit(X, y)
    coefficients = np.clip(model.coef_[0], 0.0, None)
    if coefficients.sum() == 0:
        return DEFAULT_WEIGHTS
    shares = coefficients / coefficients.sum()
    return Weights(**dict(zip(FACTORS, (float(s) for s in shares))))


def weight_error(a: Weights, b: Weights) -> float:
    """Sum of absolute differences between two weight sets (0 = identical, 2 = opposite)."""
    da, db = a.as_dict(), b.as_dict()
    return float(sum(abs(da[f] / sum(da[g] for g in FACTORS) - db[f] / sum(db[g] for g in FACTORS)) for f in FACTORS))


def expected_satisfaction(
    nurses: Sequence[Nurse],
    requests: Sequence[CareRequest],
    weights: Weights,
    hidden: Weights = HIDDEN_WEIGHTS,
    max_distance_km: float | None = None,
) -> float:
    """Average chance of a good outcome for the nurse ranked first, judged by the hidden preferences."""
    probabilities = []
    for request in requests:
        result = match(request, nurses, weights=weights, top_k=1, max_distance_km=max_distance_km)
        if result.matches:
            probabilities.append(satisfaction_probability(result.matches[0].factors, hidden))
    return float(np.mean(probabilities))


@dataclass
class LearningReport:
    default: Weights
    hidden: Weights
    learned: Weights
    satisfaction_default: float
    satisfaction_learned: float
    satisfaction_oracle: float
    curve: pd.DataFrame  # n_matches, weight_error, expected_satisfaction (mean over seeds)
    n_training_matches: int


def run_experiment(
    nurses: Sequence[Nurse],
    test_requests: Sequence[CareRequest],
    seeds: Sequence[int] = TRAIN_SEEDS,
    sizes: Sequence[int] = TRAIN_SIZES,
) -> LearningReport:
    histories = [simulate_history(nurses, max(sizes), seed=s) for s in seeds]

    rows = []
    for size in sizes:
        errors, satisfactions = [], []
        for history in histories:
            learned = fit_weights(history[:size])
            errors.append(weight_error(learned, HIDDEN_WEIGHTS))
            satisfactions.append(expected_satisfaction(nurses, test_requests, learned))
        rows.append({
            "n_matches": size,
            "weight_error": float(np.mean(errors)),
            "expected_satisfaction": float(np.mean(satisfactions)),
        })

    main_history = histories[0]
    learned = fit_weights(main_history)
    return LearningReport(
        default=DEFAULT_WEIGHTS,
        hidden=HIDDEN_WEIGHTS,
        learned=learned,
        satisfaction_default=expected_satisfaction(nurses, test_requests, DEFAULT_WEIGHTS),
        satisfaction_learned=expected_satisfaction(nurses, test_requests, learned),
        satisfaction_oracle=expected_satisfaction(nurses, test_requests, HIDDEN_WEIGHTS),
        curve=pd.DataFrame(rows),
        n_training_matches=len(main_history),
    )


def weights_table(report: LearningReport) -> pd.DataFrame:
    def norm(w: Weights) -> dict[str, float]:
        d = w.as_dict()
        total = sum(d[f] for f in FACTORS)
        return {f: d[f] / total for f in FACTORS}

    default, hidden, learned = norm(report.default), norm(report.hidden), norm(report.learned)
    return pd.DataFrame(
        {
            "Factor": [f.capitalize() for f in FACTORS],
            "Hand-set": [default[f] for f in FACTORS],
            "Hidden preference": [hidden[f] for f in FACTORS],
            "Learned": [learned[f] for f in FACTORS],
        }
    )


def render_report(report: LearningReport) -> str:
    w = weights_table(report).round(2)
    curve = report.curve.rename(
        columns={
            "n_matches": "Past matches",
            "weight_error": "Distance from hidden weights",
            "expected_satisfaction": "Chance first pick goes well",
        }
    ).round(3)
    return "\n".join(
        [
            "## Weights",
            "",
            w.to_markdown(index=False),
            "",
            f"Learned from {report.n_training_matches} simulated past matches.",
            "",
            "## Chance that the first pick goes well (100 held-out requests)",
            "",
            f"- Hand-set weights: {report.satisfaction_default:.3f}",
            f"- Learned weights: {report.satisfaction_learned:.3f}",
            f"- Hidden preferences (best possible): {report.satisfaction_oracle:.3f}",
            "",
            "## Learning curve (average of 3 simulated histories)",
            "",
            curve.to_markdown(index=False),
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Learn weights from simulated feedback.")
    parser.add_argument("--write", type=Path, help="also write the report to this markdown file")
    args = parser.parse_args()

    nurses, requests = load_dataset()
    text = render_report(run_experiment(nurses, requests))
    print(text)
    if args.write:
        args.write.write_text(
            "# Learned weights\n\nGenerated by `python -m matcher.learning`. All feedback is "
            "simulated from invented preferences, so this checks the method, not real-world "
            "performance.\n\n" + text + "\n"
        )


if __name__ == "__main__":
    main()
